const shape = (spec) => {
  const [kind, rest] = spec.length > 2 && spec[1] === ':' ? [spec[0], spec.slice(2)] : ['p', spec];
  const n = rest.split(',').map(Number);
  switch (kind) {
    case 'c': return `<circle cx="${n[0]}" cy="${n[1]}" r="${n[2]}"/>`;
    case 'C': return `<circle cx="${n[0]}" cy="${n[1]}" r="${n[2]}" fill="currentColor" stroke="none"/>`;
    case 'r': return `<rect x="${n[0]}" y="${n[1]}" width="${n[2]}" height="${n[3]}" rx="${n[4] ?? 0}"/>`;
    case 'e': return `<ellipse cx="${n[0]}" cy="${n[1]}" rx="${n[2]}" ry="${n[3]}"/>`;
    case 'F': return `<path d="${rest}" fill="currentColor" stroke="none"/>`;
    default: return `<path d="${rest}"/>`;
  }
};

const cache = new Map();

/** The glyph alone, for inline use: stroke follows currentColor. */
export function glyph(name) {
  if (!cache.has(name)) cache.set(name, (GLYPHS[name] ?? GLYPHS.spark).map(shape).join(''));
  return cache.get(name);
}

/** Dark ink on light tiles, white on the rest. */
export function inkFor(hex) {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255)
    .map((c) => (c <= 0.03928 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b > 0.36 ? '#201515' : '#FFFFFF';
}

/** An app's icon as an SVG string. Decorative: the app's name is always next to it. */
